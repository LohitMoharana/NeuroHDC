"""Generate a constant prototype ROM module: first NBITS bits of each of the 5 trained MIT-BIH prototypes
(hw/.../prototypes.dat) split into NBITS/CHUNK chunks (char 0 = MSB of chunk 0).
Usage: python gen_proto_rom.py [NBITS=256] [CHUNK=32] [MODULE=proto_rom256]
NOTE: the ASIC prototype encoder is not the trained D=4096 model; at NBITS<4096 the contents are the first
NBITS bits of the trained prototypes and only make the ROM non-trivial (datapath characterisation, not accuracy)."""
import os, sys
nbits = int(sys.argv[1]) if len(sys.argv) > 1 else 256
chunk = int(sys.argv[2]) if len(sys.argv) > 2 else 32
mod = sys.argv[3] if len(sys.argv) > 3 else "proto_rom256"
folds = nbits // chunk
kw = max(1, (folds - 1).bit_length())
root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
src = os.path.join(root, "hw/vivado/NeuroHDC/NeuroHDC.ip_user_files/mem_init_files/prototypes.dat")
protos = [l.strip()[:nbits] for l in open(src) if l.strip()]
assert len(protos) == 5 and all(len(p) == nbits for p in protos)
W = 5 * chunk
out = [f"// GENERATED by gen_proto_rom.py - do not edit. 5 classes x {folds} chunks x {chunk} bits (first {nbits} bits of trained prototypes).",
       f"module {mod} (", f"    input  wire [{kw-1}:0]   k,", f"    output reg  [{W-1}:0] words   // class c at [c*{chunk} +: {chunk}]", ");",
       "    always @(*) begin", "        case (k)"]
for k in range(folds):
    parts = [f"{chunk}'b{protos[c][chunk*k:chunk*k+chunk]}" for c in range(4, -1, -1)]
    out.append(f"            {kw}'d{k}: words = {{{', '.join(parts)}}};")
out += [f"            default: words = {W}'d0;", "        endcase", "    end", "endmodule", ""]
open(os.path.join(os.path.dirname(__file__), "rtl", f"{mod}.v"), "w").write("\n".join(out))
print("wrote", mod)
